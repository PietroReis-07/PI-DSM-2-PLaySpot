USE playspot;

CREATE TABLE PROPRIETARIO (
    ID_Proprietario INT AUTO_INCREMENT PRIMARY KEY,
    Nome VARCHAR(100) NOT NULL,
    Email VARCHAR(100) NOT NULL UNIQUE,
    Telefone CHAR(11) NOT NULL,
    CNPJ CHAR(14) NOT NULL UNIQUE,
    Cidade VARCHAR(100) NOT NULL,
    Senha_hash VARCHAR(60) NOT NULL
);

ALTER TABLE USUARIO
    ADD COLUMN Senha_hash VARCHAR(60) NOT NULL DEFAULT '';

ALTER TABLE ARENA
    DROP INDEX CEP,
    DROP INDEX CNPJ,
    MODIFY COLUMN Rua VARCHAR(60) NULL,
    MODIFY COLUMN Numero INT NULL,
    MODIFY COLUMN CEP CHAR(8) NULL,
    ADD COLUMN Cidade VARCHAR(100) NOT NULL DEFAULT '',
    ADD COLUMN Imagem VARCHAR(500) NULL,
    ADD COLUMN ID_Proprietario INT NULL,
    ADD CONSTRAINT fk_arena_proprietario
        FOREIGN KEY (ID_Proprietario)
        REFERENCES PROPRIETARIO(ID_Proprietario);
