USE playspot;

ALTER TABLE USUARIO
  ADD COLUMN Senha_hash VARCHAR(255) NOT NULL AFTER Email,
  ADD COLUMN Perfil ENUM('CLIENTE','ADMIN') NOT NULL DEFAULT 'CLIENTE',
  DROP COLUMN Idade;

ALTER TABLE ARENA
  ADD COLUMN Cidade VARCHAR(60) NOT NULL,
  ADD COLUMN Foto_url VARCHAR(255) NULL,
  ADD COLUMN ID_Usuario INT NULL,
  ADD CONSTRAINT fk_arena_usuario
    FOREIGN KEY (ID_Usuario) REFERENCES USUARIO(ID_Usuario);

ALTER TABLE RESERVA
  ADD COLUMN Status ENUM('CONFIRMADA','CANCELADA') NOT NULL DEFAULT 'CONFIRMADA';